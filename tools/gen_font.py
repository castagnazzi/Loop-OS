#!/usr/bin/env python3
"""Convert a Linux console font (PSF1/PSF2, optionally gzipped) into the 8x16
bitmap font header used by Loop-OS (kernel/drivers/font8x16.h).

usage: python3 tools/gen_font.py <font.psf[.gz]> [output.h]

The font is indexed by Latin-1 code point (0..255) using the unicode table
stored in the PSF file; code points the font lacks fall back to '?'.
Bit 0 of every row byte is the leftmost pixel.
"""

import gzip
import struct
import sys


def load(path):
    data = open(path, "rb").read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    return data


def parse(data):
    """Returns (glyphs, width, height, unicode_map: codepoint -> glyph index)."""
    if data[:2] == b"\x36\x04":                                  # PSF1
        mode, charsize = data[2], data[3]
        count = 512 if mode & 1 else 256
        glyphs = [data[4 + i * charsize:4 + (i + 1) * charsize] for i in range(count)]
        table = data[4 + count * charsize:]
        umap = {}
        if mode & 6:
            pos, idx = 0, 0
            while pos + 1 < len(table) and idx < count:
                v = struct.unpack_from("<H", table, pos)[0]
                pos += 2
                if v == 0xFFFF:
                    idx += 1
                elif v == 0xFFFE:
                    # a sequence follows (combining); skip until the terminator
                    while pos + 1 < len(table) and struct.unpack_from("<H", table, pos)[0] != 0xFFFF:
                        pos += 2
                else:
                    umap.setdefault(v, idx)
        return glyphs, 8, charsize, umap

    if data[:4] == b"\x72\xb5\x4a\x86":                          # PSF2
        (_, _, hsize, flags, count, charsize, height, width) = struct.unpack_from("<8I", data, 0)
        glyphs = [data[hsize + i * charsize:hsize + (i + 1) * charsize] for i in range(count)]
        umap = {}
        if flags & 1:
            pos = hsize + count * charsize
            idx = 0
            text = data[pos:]
            i = 0
            while i < len(text) and idx < count:
                b = text[i]
                if b == 0xFF:
                    idx += 1
                    i += 1
                elif b == 0xFE:
                    while i < len(text) and text[i] != 0xFF:
                        i += 1
                else:
                    n = 1 if b < 0x80 else 2 if b < 0xE0 else 3 if b < 0xF0 else 4
                    cp = ord(text[i:i + n].decode("utf-8", "replace"))
                    umap.setdefault(cp, idx)
                    i += n
        return glyphs, width, height, umap

    raise SystemExit("not a PSF font")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else "kernel/drivers/font8x16.h"
    glyphs, width, height, umap = parse(load(src))
    if width != 8 or height != 16:
        raise SystemExit("need an 8x16 font, got %dx%d" % (width, height))

    fallback = umap.get(ord("?"), 0)
    blank = umap.get(ord(" "), 0)

    def rev(b):
        return int("{:08b}".format(b)[::-1], 2)

    rows = []
    for cp in range(256):
        if cp < 32 or 127 <= cp < 160:
            gi = blank
        else:
            gi = umap.get(cp, fallback)
        rows.append([rev(b) for b in glyphs[gi][:16]])

    with open(dst, "w", newline="\n") as f:
        f.write("/* 8x16 bitmap font indexed by Latin-1 code (0..255).\n")
        f.write(" * Generated by tools/gen_font.py from %s (Terminus, SIL OFL 1.1,\n" % src.replace("\\", "/").split("/")[-1])
        f.write(" * (c) Dimitar Zhekov). Bit 0 of each row byte is the leftmost pixel. */\n\n")
        f.write("#ifndef _KERNEL_DRIVERS_FONT8X16_H\n#define _KERNEL_DRIVERS_FONT8X16_H\n\n#include <stdint.h>\n\n")
        f.write("static const uint8_t font8x16[256][16] = {\n")
        for cp, r in enumerate(rows):
            f.write("    { " + ", ".join("0x%02X" % b for b in r) + " },\n")
        f.write("};\n\n#endif\n")
    print("wrote %s (%d glyphs mapped from unicode)" % (dst, len([c for c in range(256) if c in umap])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
