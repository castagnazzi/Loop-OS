#!/usr/bin/env python3
"""Turn an image into the boot-screen logo (kernel/drivers/logo.h).

usage: python tools/gen_logo.py <image> [height_px] [output.h]

  <image>      PNG/GIF/JPG. A PNG with transparency is used as is. An image
               with a plain or vertically-graded background (like a mascot
               on a dark gradient) gets that background keyed out: the
               background colour is sampled at the left/right edge of every
               row. For animated GIFs the first frame is used.
  height_px    logo height on screen, default 40 (the title bar is 56 tall)
  output.h     default kernel/drivers/logo.h

Needs Pillow (pip install pillow). The result is a C array of 0xAARRGGBB
pixels; the kernel alpha-blends it over the title bar colour at boot.
"""

import sys
from PIL import Image


def has_transparency(img):
    if img.mode != "RGBA":
        return False
    return img.getchannel("A").getextrema()[0] < 250


def key_out_background(img):
    """Estimate alpha from the difference to the row's edge background."""
    w, h = img.size
    px = img.load()
    out = Image.new("RGBA", (w, h))
    op = out.load()
    for y in range(h):
        edge = [px[x, y][:3] for x in (1, 2, 3, w - 4, w - 3, w - 2)]
        bg = tuple(sorted(c[i] for c in edge)[len(edge) // 2] for i in range(3))
        for x in range(w):
            r, g, b, _ = px[x, y]
            diff = abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2])
            alpha = max(0, min(255, (diff - 14) * 255 // 50))
            op[x, y] = (r, g, b, alpha)
    return out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    src = sys.argv[1]
    height = int(sys.argv[2]) if len(sys.argv) > 2 else 40
    dst = sys.argv[3] if len(sys.argv) > 3 else "kernel/drivers/logo.h"

    img = Image.open(src)
    img.seek(0)
    img = img.convert("RGBA")
    if not has_transparency(img):
        img = key_out_background(img)

    # Crop to the visible part, with a 1 pixel margin
    bbox = img.getchannel("A").point(lambda a: 255 if a > 24 else 0).getbbox()
    if not bbox:
        print("error: nothing visible in the image")
        return 1
    l, t, r, b = bbox
    img = img.crop((max(0, l - 1), max(0, t - 1), min(img.width, r + 1), min(img.height, b + 1)))

    # Resize with premultiplied alpha so edges do not pick up a dark halo
    width = max(1, round(img.width * height / img.height))
    img = img.convert("RGBa").resize((width, height), Image.LANCZOS).convert("RGBA")

    pixels = []
    for y in range(height):
        for x in range(width):
            r, g, b, a = img.getpixel((x, y))
            pixels.append((a << 24) | (r << 16) | (g << 8) | b)

    with open(dst, "w", newline="\n") as f:
        f.write("/* Generated by tools/gen_logo.py from %s - do not edit by hand.\n" % src.replace("\\", "/").split("/")[-1])
        f.write(" * 0xAARRGGBB pixels, row by row. */\n\n")
        f.write("#ifndef _KERNEL_DRIVERS_LOGO_H\n#define _KERNEL_DRIVERS_LOGO_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define LOGO_W %d\n#define LOGO_H %d\n\n" % (width, height))
        f.write("static const uint32_t logo_argb[LOGO_W * LOGO_H] = {\n")
        for i in range(0, len(pixels), 8):
            f.write("    " + ", ".join("0x%08X" % p for p in pixels[i:i + 8]) + ",\n")
        f.write("};\n\n#endif\n")

    print("wrote %s (%dx%d)" % (dst, width, height))
    return 0


if __name__ == "__main__":
    sys.exit(main())
